/**
 * Testes da camada de compatibilidade PostgREST → MariaDB (base de TESTE com os dados de exemplo).
 *   set -a; . ./.env.local; set +a
 *   npx tsx --conditions=react-server --tsconfig tsconfig.json tests/db-compat.test.ts
 */
import { serviceClient, makeDbClient } from '../src/lib/db/server-client'

let pass = 0, fail = 0
const ok = (c: unknown, name: string, extra?: unknown) => { c ? pass++ : fail++; console.log(`${c ? '✔' : '✗'} ${name}${extra !== undefined && !c ? ' — ' + JSON.stringify(extra).slice(0, 300) : ''}`) }
const db = serviceClient()
const JOAO = '11111111-1111-4111-8111-111111111111'

async function main() {
  // embeds via FK e via "ponte" auth_users (orders.user_id → profiles)
  const o = await db.from('orders').select('*, profiles(full_name, email), order_items(*)').order('created_at', { ascending: false })
  ok(!o.error && o.data!.length >= 2 && o.data!.some((r: any) => r.profiles?.full_name === 'João Conceição'), "orders → profiles (m2o via auth_users)", o.error ?? o.data)
  ok(o.data!.every((r: any) => Array.isArray(r.order_items)), 'orders → order_items (o2m, array)')
  const t = await db.from('tickets').select('*, ticket_messages(count)').eq('profile_id', JOAO)
  ok(t.data!.some((r: any) => r.ticket_messages[0].count >= 3), 'ticket_messages(count) → [{count}]', t.data)
  const p = await db.from('profiles').select('id, full_name, services(id, plans(name))').eq('id', JOAO).single()
  ok(Array.isArray(p.data.services) && p.data.services.length === 1 && 'plans' in p.data.services[0], 'embed aninhado services(plans(name))', p)
  const s = await db.from('services').select('id, status, price, plan:plans(name, type), hosting_accounts(primary_domain, status)').eq('profile_id', JOAO)
  ok(s.data![0].plan === null && s.data![0].hosting_accounts[0].primary_domain === 'conceicao.ao', 'alias plan:plans e o2m hosting_accounts', s.data)
  const c = await db.from('profiles').select('id, clients(company_name)').eq('id', JOAO).single()
  ok(c.data.clients?.company_name === 'Conceição & Filhos, Lda', 'one-to-one (clients.profile_id UNIQUE) → objeto', c.data)
  const pf = await db.from('products').select('slug, product_features(feature, position)').eq('active', true).order('position', { ascending: true }).order('position', { referencedTable: 'product_features', ascending: false }).limit(2)
  ok(pf.data!.length === 2 && pf.data![0].product_features.length > 1 && pf.data![0].product_features[0].position >= pf.data![0].product_features[1].position, 'order referencedTable + limit no topo', pf.data?.[0])
  // filtros
  const or = await db.from('profiles').select('email').or(`full_name.ilike.%joão%,email.ilike.%MARIA%,id.eq.00000000-0000-0000-0000-000000000000`)
  ok(or.data!.length === 2, 'or() com ilike (case-insensitive) e eq', or.data)
  const nn = await db.from('whm_accounts').select('id').not('profile_id', 'is', null)
  ok(nn.data!.length === 1, 'not(col, is, null)')
  const isn = await db.from('services').select('id').is('plan_id', null)
  ok(isn.data!.length >= 1, 'is(col, null)')
  const inn = await db.from('site_domains').select('extension').in('extension', ['.ao', '.co.ao']).order('extension')
  ok(inn.data!.map((r: any) => r.extension).join() === '.ao,.co.ao', 'in() + order', inn.data)
  const rf = await db.from('site_domains').select('extension').filter('extension', 'in', '(".ao",".old")')
  ok(rf.data!.length === 2, "filter(col, 'in', '(a,b)')", rf)
  const cnt = await db.from('product_features').select('id', { count: 'exact', head: true })
  ok(cnt.count === 392 && cnt.data === null, 'count exact + head', cnt)
  const rg = await db.from('products').select('slug', { count: 'exact' }).order('slug').range(10, 14)
  ok(rg.data!.length === 5 && rg.count === 54, 'range() + count', rg.count)
  const ns = await db.from('invoices').select('paid_at').order('paid_at', { ascending: false })
  ok(ns.data![0].paid_at === null, 'ordem DESC com NULLS FIRST (como PostgreSQL)', ns.data)
  const na = await db.from('invoices').select('paid_at').order('paid_at', { ascending: true })
  ok(na.data![na.data!.length - 1].paid_at === null, 'ordem ASC com NULLS LAST (como PostgreSQL)')
  const cs = await db.from('site_banners').select('title').contains('features', ['SSL grátis'])
  ok(cs.data!.length === 1, 'contains() em array (JSON_CONTAINS)', cs)
  const jp = await db.from('whm_accounts').select('id, plan:raw_metadata->>plan').eq('raw_metadata->>plan', 'business')
  ok(jp.data!.length === 1 && jp.data![0].plan === 'business', 'caminho JSON col->>chave', jp)
  // tipos devolvidos
  const inv = await db.from('invoices').select('total, items, due_date, issue_date').eq('invoice_number', 'VH-202603-0001').single()
  ok(inv.data.total === 45999.99 && typeof inv.data.total === 'number', 'DECIMAL → number (como PostgREST)', inv.data)
  ok(Array.isArray(inv.data.items) && inv.data.items[1].name === 'Domínio .ao', 'JSON → objeto com acentos')
  ok(inv.data.due_date === '2026-03-08T00:00:00+00:00' && inv.data.issue_date.length === 10, 'datas ISO-8601 com fuso', inv.data)
  const pr = await db.from('profiles').select('created_at').eq('id', JOAO).single()
  ok(/\.\d{1,6}\+00:00$/.test(pr.data.created_at) || /:\d\d\+00:00$/.test(pr.data.created_at), 'microssegundos preservados', pr.data)
  const bp = await db.from('banner_pages').select('highlights, is_active, overlay_opacity').limit(1).single()
  ok(Array.isArray(bp.data.highlights) && bp.data.is_active === true && typeof bp.data.overlay_opacity === 'number', 'text[] → array, boolean → true/false')
  // erros
  const one = await db.from('profiles').select('id').single()
  ok(one.error?.code === 'PGRST116', 'single() com várias linhas → PGRST116')
  const mb = await db.from('profiles').select('id').eq('id', '00000000-0000-0000-0000-000000000000').maybeSingle()
  ok(mb.data === null && mb.error === null, 'maybeSingle() sem linhas → null')
  const dup = await db.from('site_domains').insert({ extension: '.ao', price_annual: 1 })
  ok(dup.error?.code === '23505', 'chave duplicada → 23505', dup.error)
  const badCol = await db.from('profiles').select('nao_existe')
  ok(badCol.error?.code === '42703', 'coluna inexistente → erro', badCol.error)
  const inj = await db.from('profiles').select('id').eq('email', "x' OR '1'='1")
  ok(inj.data!.length === 0, 'valores são parametrizados (sem injeção SQL)')
  const injCol = await db.from('profiles').select('id').order('id; DROP TABLE profiles')
  ok(!!injCol.error, 'identificadores validados contra o schema')
  // escrita
  const ins = await db.from('notifications').insert([{ profile_id: JOAO, title: 'Olá', message: 'Fatura disponível — ação necessária' }, { profile_id: JOAO, title: 'B', message: 'b' }]).select('id, title, is_read, created_at')
  ok(ins.data!.length === 2 && ins.data![0].title === 'Olá' && ins.data![0].is_read === false && ins.data![0].id, 'insert múltiplo + select (ids gerados, defaults)', ins)
  const ids = ins.data!.map((r: any) => r.id)
  const up = await db.from('notifications').update({ is_read: true }).in('id', ids).select('id')
  ok(up.data!.length === 2, 'update().select()')
  const ups = await db.from('clients').upsert({ profile_id: JOAO, notes: 'upsert ok' }, { onConflict: 'profile_id' }).select('id, notes, company_name').single()
  ok(ups.data?.notes === 'upsert ok' && ups.data.company_name === 'Conceição & Filhos, Lda', 'upsert onConflict preserva colunas não enviadas', ups)
  const before = await db.from('clients').select('updated_at').eq('profile_id', JOAO).single()
  await new Promise((r) => setTimeout(r, 20))
  await db.from('clients').update({ notes: 'x' }).eq('profile_id', JOAO)
  const after = await db.from('clients').select('updated_at').eq('profile_id', JOAO).single()
  ok(after.data.updated_at > before.data.updated_at, 'updated_at automático (porta do trigger set_updated_at)')
  const del = await db.from('notifications').delete().in('id', ids).select('id')
  ok(del.data!.length === 2, 'delete().select() devolve as linhas apagadas')
  const gen = await db.from('domains').select('full_domain').eq('name', 'conceicao').single()
  ok(gen.data.full_domain === 'conceicao.ao', 'coluna gerada full_domain')
  const pay = await db.from('payments').insert({ invoice_id: '88888888-8888-4888-8888-888888888882', profile_id: '22222222-2222-4222-8222-222222222222', amount: 3500.5, proof_url: '2222/p.png' }).select('id').single()
  const inv2 = await db.from('invoices').select('proof_file').eq('id', '88888888-8888-4888-8888-888888888882').single()
  ok(inv2.data.proof_file === '2222/p.png', 'porta do trigger sync_invoice_proof_file', inv2.data)
  await db.from('payments').delete().eq('id', pay.data.id)
  await db.from('invoices').update({ proof_file: null }).eq('id', '88888888-8888-4888-8888-888888888882')
  // RLS (papel authenticated)
  const cli = makeDbClient(async () => ({ role: 'authenticated', uid: JOAO, profileRole: 'client' }))
  const own = await cli.from('invoices').select('id, profiles(full_name)')
  ok(own.data!.length === 1 && own.data![0].profiles.full_name === 'João Conceição', 'RLS: cliente vê só as suas faturas, com embed')
  const emb = await cli.from('tickets').select('id, profiles(full_name)').eq('profile_id', '22222222-2222-4222-8222-222222222222')
  ok(emb.data!.length === 0, 'RLS: filtro por outro profile_id não devolve nada')
  const rpc = await db.rpc('get_client_invoices', { p_user_id: JOAO, p_search: 'conceicao' })
  ok(rpc.data.total === 1 && rpc.data.invoices[0].order_items.length === 2, 'RPC get_client_invoices com pesquisa', rpc)
  const rec = await db.rpc('reconcile_unprovisioned_orders')
  ok(rec.data.ok === true, 'RPC reconcile_unprovisioned_orders', rec)
  console.log(`\n${pass} passou, ${fail} falhou`)
  process.exit(fail ? 1 : 0)
}
main().catch((e) => { console.error(e); process.exit(1) })
